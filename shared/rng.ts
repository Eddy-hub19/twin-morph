/**
 * Детерминированный ГПСЧ (mulberry32) — от него зависит, что оба клиента в
 * co-op, получив от сервера ОДИНАКОВЫЙ числовой seed, генерируют побитово
 * одинаковую карту (расположение камня/руды, звёзд, пузырьков, факела, норы,
 * стража и врагов), не обмениваясь самой картой целиком. Обычный Math.random()
 * для этого не годится — у каждого клиента он даёт свою последовательность.
 *
 * Чистая функция без побочных эффектов — как и stepPlayerState в
 * game-protocol.ts, безопасно шарится между сервером (генерирует seed) и
 * клиентом (генерирует саму карту из этого seed).
 */
export type Rng = () => number

export function createRng(seed: number): Rng {
  // mulberry32: маленький, быстрый, достаточно качественный для процедурной
  // генерации уровня 32-битный ГПСЧ.
  let state = seed >>> 0

  return function rng(): number {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** Свежий целочисленный seed — сервер вызывает это при создании нового уровня/эпохи. */
export function randomSeed(): number {
  return Math.floor(Math.random() * 0xffffffff)
}
